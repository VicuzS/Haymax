// Pool PostgreSQL, esquema y helpers compartidos de persistencia.
const { Pool, types } = require("pg");
require("dotenv").config();

// PostgreSQL bigint/DATE se exponen como tipos JS cómodos para la API.
types.setTypeParser(20, (value) => Number(value));
types.setTypeParser(1082, (value) => value);

const pool = new Pool({
  connectionString: process.env.DATABASE_URL || "postgres://haymax:haymax_dev_password@localhost:5432/haymax",
  max: Number(process.env.PG_POOL_MAX) || 10,
});

const SCHEMA = `
CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  nombre TEXT NOT NULL,
  foto_url TEXT,
  distrito TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sesiones_revocadas (
  token_hash TEXT PRIMARY KEY,
  expires_at BIGINT NOT NULL,
  revocado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hogares (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  distrito TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hogar_integrantes (
  hogar_id BIGINT NOT NULL REFERENCES hogares(id) ON DELETE CASCADE,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  rol TEXT NOT NULL DEFAULT 'miembro' CHECK (rol IN ('admin','miembro')),
  PRIMARY KEY (hogar_id, usuario_id)
);

CREATE TABLE IF NOT EXISTS catalogo_productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE,
  categoria TEXT NOT NULL,
  unidad_medida_base TEXT NOT NULL DEFAULT 'und'
);

CREATE TABLE IF NOT EXISTS despensa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hogar_id BIGINT NOT NULL REFERENCES hogares(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES catalogo_productos(id),
  nombre TEXT NOT NULL,
  cantidad DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
  unidad_medida TEXT NOT NULL DEFAULT 'und',
  fecha_vencimiento DATE,
  ubicacion TEXT NOT NULL DEFAULT 'Despensa',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS recetas (
  id TEXT PRIMARY KEY,
  titulo TEXT NOT NULL,
  descripcion TEXT,
  imagen TEXT,
  porciones INTEGER NOT NULL DEFAULT 1,
  tiempo_preparacion_min INTEGER NOT NULL DEFAULT 0,
  dificultad TEXT NOT NULL DEFAULT 'facil' CHECK (dificultad IN ('facil','media','dificil')),
  precio DOUBLE PRECISION NOT NULL DEFAULT 0,
  distrito TEXT,
  nutri_calorias INTEGER NOT NULL DEFAULT 0,
  nutri_proteinas DOUBLE PRECISION NOT NULL DEFAULT 0,
  nutri_carbohidratos DOUBLE PRECISION NOT NULL DEFAULT 0,
  nutri_grasas DOUBLE PRECISION NOT NULL DEFAULT 0,
  nutri_fibra DOUBLE PRECISION NOT NULL DEFAULT 0,
  pasos TEXT NOT NULL DEFAULT '[]',
  autor_id BIGINT REFERENCES usuarios(id),
  publica BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS receta_ingredientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receta_id TEXT NOT NULL REFERENCES recetas(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES catalogo_productos(id),
  nombre TEXT NOT NULL,
  cantidad DOUBLE PRECISION NOT NULL DEFAULT 1,
  unidad_medida TEXT NOT NULL DEFAULT 'und',
  opcional BOOLEAN NOT NULL DEFAULT FALSE,
  orden INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS planes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hogar_id BIGINT NOT NULL REFERENCES hogares(id) ON DELETE CASCADE,
  receta_id TEXT NOT NULL REFERENCES recetas(id) ON DELETE CASCADE,
  fecha TEXT NOT NULL,
  comida TEXT NOT NULL CHECK (comida IN ('desayuno','almuerzo','cena')),
  porciones INTEGER NOT NULL DEFAULT 1,
  completado BOOLEAN NOT NULL DEFAULT FALSE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS compras (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hogar_id BIGINT NOT NULL REFERENCES hogares(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES catalogo_productos(id),
  nombre TEXT NOT NULL,
  cantidad TEXT NOT NULL DEFAULT '1',
  unidad_medida TEXT,
  seccion TEXT NOT NULL DEFAULT 'Mercado de abastos',
  comprado BOOLEAN NOT NULL DEFAULT FALSE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS favoritos (
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  receta_id TEXT NOT NULL REFERENCES recetas(id) ON DELETE CASCADE,
  guardado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (usuario_id, receta_id)
);

CREATE INDEX IF NOT EXISTS idx_despensa_hogar ON despensa(hogar_id);
CREATE INDEX IF NOT EXISTS idx_planes_hogar ON planes(hogar_id, fecha);
CREATE INDEX IF NOT EXISTS idx_compras_hogar ON compras(hogar_id);
CREATE INDEX IF NOT EXISTS idx_ingredientes ON receta_ingredientes(receta_id);
`;

async function initializeSchema() {
  let ultimoError;
  for (let intento = 0; intento < 20; intento += 1) {
    try {
      return await pool.query(SCHEMA);
    } catch (error) {
      ultimoError = error;
      if (intento < 19) await new Promise((resolve) => setTimeout(resolve, 500));
    }
  }
  throw ultimoError;
}

const schemaReady = initializeSchema();

function conCliente(client) {
  const ejecutar = async (sql, args) => {
    await schemaReady;
    let parametro = 0;
    const traducido = sql.replace(/\?/g, () => `$${++parametro}`);
    return client.query(traducido, args);
  };
  return {
    all: async (sql, ...args) => (await ejecutar(sql, args)).rows,
    get: async (sql, ...args) => (await ejecutar(sql, args)).rows[0],
    run: async (sql, ...args) => {
      const result = await ejecutar(sql, args);
      return { changes: result.rowCount, rows: result.rows, row: result.rows[0] };
    },
  };
}

const q = conCliente(pool);
const db = {
  pool,
  transaction: async (callback) => {
    await schemaReady;
    const client = await pool.connect();
    const tx = conCliente(client);
    try {
      await client.query("BEGIN");
      const result = await callback(tx);
      await client.query("COMMIT");
      return result;
    } catch (error) {
      await client.query("ROLLBACK");
      throw error;
    } finally {
      client.release();
    }
  },
};

async function hogarDe(usuarioId) {
  const fila = await q.get(
    "SELECT hogar_id FROM hogar_integrantes WHERE usuario_id = ? ORDER BY hogar_id LIMIT 1",
    usuarioId
  );
  if (fila) return fila.hogar_id;

  return db.transaction(async (tx) => {
    const existente = await tx.get(
      "SELECT hogar_id FROM hogar_integrantes WHERE usuario_id = ? ORDER BY hogar_id LIMIT 1",
      usuarioId
    );
    if (existente) return existente.hogar_id;
    const u = await tx.get("SELECT nombre FROM usuarios WHERE id = ?", usuarioId);
    if (!u) return null;
    const r = await tx.run("INSERT INTO hogares (nombre) VALUES (?) RETURNING id", `Hogar de ${u.nombre || "usuario"}`);
    const hogarId = r.row.id;
    await tx.run(
      "INSERT INTO hogar_integrantes (hogar_id, usuario_id, rol) VALUES (?, ?, 'admin') ON CONFLICT DO NOTHING",
      hogarId,
      usuarioId
    );
    return hogarId;
  });
}

async function productoId(nombre, categoria, unidad) {
  if (!nombre) return null;
  const existente = await q.get(
    "SELECT id FROM catalogo_productos WHERE lower(nombre) = lower(?)",
    nombre
  );
  if (existente) return existente.id;
  const r = await q.run(
    "INSERT INTO catalogo_productos (nombre, categoria, unidad_medida_base) VALUES (?, ?, ?) RETURNING id",
    nombre,
    categoria || "Otros",
    unidad || "und"
  );
  return r.row.id;
}

module.exports = { db, q, hogarDe, productoId, schemaReady };
